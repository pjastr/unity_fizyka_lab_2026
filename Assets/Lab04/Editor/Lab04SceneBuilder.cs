using System;
using System.IO;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.Rendering;

namespace Lab04.EditorTools
{
    /// <summary>
    /// Generator sceny Lab04_Proca: materiały fizyczne, materiały URP, prefaby (z wariantami) i scena.
    /// Wszystko zgodnie z instrukcją lab04/proca_i_wieza.md (kroki 1-6).
    /// Menu: Lab04 > Generuj scenę i prefaby. Przy pierwszym otwarciu projektu scena generuje się sama.
    /// </summary>
    [InitializeOnLoad]
    public static class Lab04SceneBuilder
    {
        const string Root = "Assets/Lab04";
        const string PrefabDir = Root + "/Prefabs";
        const string MatDir = Root + "/Materials";
        const string PhysDir = Root + "/Physics";
        const string SceneDir = Root + "/Scenes";
        public const string ScenePath = SceneDir + "/Lab04_Proca.unity";
        const string AutoGenKey = "Lab04_AutoGenerated";

        // =====================================================================
        //  AUTOMATYCZNE GENEROWANIE PRZY PIERWSZYM OTWARCIU PROJEKTU
        // =====================================================================

        static int s_Attempts;

        static Lab04SceneBuilder()
        {
            if (Application.isBatchMode) return;
            EditorApplication.delayCall += TryAutoGenerate;
        }

        static void TryAutoGenerate()
        {
            if (File.Exists(ScenePath) || SessionState.GetBool(AutoGenKey, false))
                return;

            // Przy pierwszym imporcie shadery URP mogą jeszcze nie być gotowe - spróbuj ponownie za chwilę.
            if (EditorApplication.isCompiling || EditorApplication.isUpdating || Shader.Find("Universal Render Pipeline/Lit") == null)
            {
                if (++s_Attempts < 50)
                    EditorApplication.delayCall += TryAutoGenerate;
                return;
            }

            SessionState.SetBool(AutoGenKey, true);
            try
            {
                GenerateAll();
                EditorSceneManager.OpenScene(ScenePath);
                Debug.Log("[Lab04] Wygenerowano scenę " + ScenePath + ". Naciśnij Play.");
            }
            catch (Exception e)
            {
                Debug.LogException(e);
                Debug.LogError("[Lab04] Automatyczne generowanie nie powiodło się - użyj menu Lab04 > Generuj scenę i prefaby.");
            }
        }

        // =====================================================================
        //  MENU
        // =====================================================================

        [MenuItem("Lab04/Generuj scenę i prefaby", priority = 0)]
        public static void GenerateMenu()
        {
            if (!EditorSceneManager.SaveCurrentModifiedScenesIfUserWantsTo())
                return;
            GenerateAll();
            EditorSceneManager.OpenScene(ScenePath);
            EditorUtility.DisplayDialog("Lab04",
                "Wygenerowano materiały, prefaby i scenę:\n" + ScenePath +
                "\n\nUwaga: ponowne generowanie nadpisuje ręczne zmiany w scenie i prefabach.", "OK");
        }

        [MenuItem("Lab04/Otwórz scenę i uruchom Play", priority = 1)]
        public static void OpenAndPlay()
        {
            if (!EditorSceneManager.SaveCurrentModifiedScenesIfUserWantsTo())
                return;
            if (!File.Exists(ScenePath))
                GenerateAll();
            EditorSceneManager.OpenScene(ScenePath);
            EditorApplication.isPlaying = true;
        }

        [MenuItem("Lab04/Otwórz instrukcję", priority = 40)]
        public static void OpenInstructions()
        {
            string p = Path.GetFullPath("Docs/proca_i_wieza.md");
            if (!File.Exists(p)) p = Path.GetFullPath("README.md");
            if (File.Exists(p)) EditorUtility.OpenWithDefaultApp(p);
        }

        /// <summary>Unity.exe -batchmode -projectPath ... -executeMethod Lab04.EditorTools.Lab04SceneBuilder.BatchGenerate</summary>
        public static void BatchGenerate()
        {
            int code = 0;
            try
            {
                GenerateAll();
                Debug.Log("[Lab04] BatchGenerate: OK");
            }
            catch (Exception e)
            {
                Debug.LogException(e);
                code = 1;
            }
            EditorApplication.Exit(code);
        }

        // =====================================================================
        //  GENEROWANIE
        // =====================================================================

        public static void GenerateAll()
        {
            EnsureFolders();

            // --- krok 1: materiały fizyczne ---
            var pmGround = PhysMat("PM_Ground", 0.6f, 0.6f, 0f);
            var pmWood = PhysMat("PM_Drewno", 0.5f, 0.6f, 0.1f);
            var pmStone = PhysMat("PM_Kamien", 0.7f, 0.8f, 0f);
            var pmGlass = PhysMat("PM_Szklo", 0.15f, 0.2f, 0.2f);
            var pmRubber = PhysMat("PM_Guma", 0.8f, 0.9f, 0.6f, PhysicsMaterialCombine.Average, PhysicsMaterialCombine.Maximum);

            // --- krok 1: materiały wyglądu (URP) ---
            var mWood = Mat("M_Drewno", new Color(0.6f, 0.42f, 0.25f));
            var mStone = Mat("M_Kamien", new Color(0.52f, 0.54f, 0.57f));
            var mGlass = TransparentMat("M_Szklo", new Color(0.65f, 0.85f, 1f, 0.5f));
            var mTarget = Mat("M_Cel", new Color(0.35f, 0.8f, 0.3f));
            var mBall = Mat("M_Pocisk", new Color(0.86f, 0.2f, 0.18f));
            var mGround = Mat("M_Ground", new Color(0.55f, 0.6f, 0.55f));
            var mBarrel = Mat("M_Lufa", new Color(0.2f, 0.21f, 0.24f));
            var mLine = UnlitMat("M_Linia", new Color(1f, 0.85f, 0.2f));

            // --- krok 2.4: prefaby ---
            GameObject wood = BlockPrefab("Blok_Drewno", density: 2f, strength: 6f, pmWood, mWood);
            GameObject glass = BlockVariant(wood, "Blok_Szklo", density: 1.5f, strength: 2f, pmGlass, mGlass);
            GameObject stone = BlockVariant(wood, "Blok_Kamien", density: 6f, strength: 40f, pmStone, mStone);
            GameObject target = TargetPrefab(pmWood, mTarget);
            GameObject ball = ProjectilePrefab(pmRubber, mBall);

            // --- scena ---
            var scene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);
            Lighting();

            // podłoga (statyczna)
            var ground = GameObject.CreatePrimitive(PrimitiveType.Cube);
            ground.name = "Ground";
            ground.transform.position = new Vector3(0f, -0.5f, 6f);
            ground.transform.localScale = new Vector3(30f, 1f, 40f);
            ground.GetComponent<Collider>().sharedMaterial = pmGround;
            ground.GetComponent<Renderer>().sharedMaterial = mGround;

            // --- krok 3: wieża ---
            var towerGo = new GameObject("Wieza");
            towerGo.transform.position = new Vector3(0f, 0f, 12f);
            var tower = towerGo.AddComponent<TowerBuilder>();
            var towerSo = new SerializedObject(tower);
            var arr = towerSo.FindProperty("floorPrefabs");
            arr.arraySize = 3;
            arr.GetArrayElementAtIndex(0).objectReferenceValue = wood.GetComponent<Block>();
            arr.GetArrayElementAtIndex(1).objectReferenceValue = glass.GetComponent<Block>();
            arr.GetArrayElementAtIndex(2).objectReferenceValue = stone.GetComponent<Block>();
            towerSo.FindProperty("targetPrefab").objectReferenceValue = target.GetComponent<Target>();
            towerSo.FindProperty("floors").intValue = 3;
            towerSo.ApplyModifiedPropertiesWithoutUndo();

            // --- krok 4.1: wyrzutnia ---
            var launcherGo = new GameObject("Wyrzutnia");
            launcherGo.transform.position = new Vector3(0f, 1f, 0f);
            var lr = launcherGo.AddComponent<LineRenderer>();
            lr.widthMultiplier = 0.05f;
            lr.sharedMaterial = mLine;
            lr.useWorldSpace = true;
            lr.shadowCastingMode = ShadowCastingMode.Off;
            lr.receiveShadows = false;
            lr.positionCount = 0;

            var barrel = GameObject.CreatePrimitive(PrimitiveType.Cylinder);
            barrel.name = "Lufa";
            UnityEngine.Object.DestroyImmediate(barrel.GetComponent<Collider>()); // ważne - patrz instrukcja 4.1
            barrel.transform.SetParent(launcherGo.transform, false);
            barrel.transform.localPosition = new Vector3(0f, 0f, 0.6f);
            barrel.transform.localRotation = Quaternion.Euler(90f, 0f, 0f);
            barrel.transform.localScale = new Vector3(0.3f, 0.6f, 0.3f);
            barrel.GetComponent<Renderer>().sharedMaterial = mBarrel;

            var muzzle = new GameObject("Wylot");
            muzzle.transform.SetParent(launcherGo.transform, false);
            muzzle.transform.localPosition = new Vector3(0f, 0f, 1.3f);

            var launcher = launcherGo.AddComponent<Launcher>();
            var lso = new SerializedObject(launcher);
            lso.FindProperty("projectilePrefab").objectReferenceValue = ball.GetComponent<Rigidbody>();
            lso.FindProperty("muzzle").objectReferenceValue = muzzle.transform;
            lso.ApplyModifiedPropertiesWithoutUndo();
            launcherGo.transform.rotation = Quaternion.Euler(-20f, 0f, 0f); // podgląd w trybie edycji

            // --- krok 5: sędzia ---
            var judgeGo = new GameObject("Sedzia");
            var judge = judgeGo.AddComponent<LevelJudge>();
            var jso = new SerializedObject(judge);
            jso.FindProperty("launcher").objectReferenceValue = launcher;
            jso.FindProperty("tower").objectReferenceValue = tower;
            jso.ApplyModifiedPropertiesWithoutUndo();

            // HUD (pomocniczy)
            var hud = judgeGo.AddComponent<LabHud>();
            var hso = new SerializedObject(hud);
            hso.FindProperty("launcher").objectReferenceValue = launcher;
            hso.FindProperty("judge").objectReferenceValue = judge;
            hso.ApplyModifiedPropertiesWithoutUndo();

            // --- krok 6.2: kamera ---
            var camGo = new GameObject("Main Camera");
            camGo.tag = "MainCamera";
            var cam = camGo.AddComponent<Camera>();
            cam.fieldOfView = 60f;
            cam.farClipPlane = 300f;
            camGo.AddComponent<AudioListener>();
            camGo.transform.position = new Vector3(4f, 4f, -5f);
            camGo.transform.rotation = Quaternion.Euler(10f, -13f, 0f);
            var chase = camGo.AddComponent<ChaseCamera>();
            var cso = new SerializedObject(chase);
            cso.FindProperty("launcher").objectReferenceValue = launcher;
            cso.ApplyModifiedPropertiesWithoutUndo();

            // --- krok 6.1: szyba do eksperymentu z tunelowaniem (domyślnie wyłączona) ---
            var pane = GameObject.CreatePrimitive(PrimitiveType.Cube);
            pane.name = "Szyba";
            pane.transform.position = new Vector3(0f, 1.5f, 6f);
            pane.transform.localScale = new Vector3(4f, 3f, 0.05f);
            pane.GetComponent<Renderer>().sharedMaterial = mGlass;
            pane.SetActive(false);

            EditorSceneManager.SaveScene(scene, ScenePath);
            EditorBuildSettings.scenes = new[] { new EditorBuildSettingsScene(ScenePath, true) };
            AssetDatabase.SaveAssets();
            AssetDatabase.Refresh();
            Debug.Log("[Lab04] Zapisano scenę: " + ScenePath);
        }

        // =====================================================================
        //  PREFABY
        // =====================================================================

        static GameObject BlockPrefab(string name, float density, float strength, PhysicsMaterial pm, Material mat)
        {
            var go = GameObject.CreatePrimitive(PrimitiveType.Cube);
            go.name = name;
            go.AddComponent<Rigidbody>();
            var block = go.AddComponent<Block>();
            go.GetComponent<Collider>().sharedMaterial = pm;
            go.GetComponent<Renderer>().sharedMaterial = mat;
            SetBlockFields(block, density, strength);
            return SavePrefab(go, name);
        }

        /// <summary>Wariant prefabu: instancja prefabu bazowego zapisana jako nowy prefab = Prefab Variant.</summary>
        static GameObject BlockVariant(GameObject basePrefab, string name, float density, float strength, PhysicsMaterial pm, Material mat)
        {
            string path = $"{PrefabDir}/{name}.prefab";
            AssetDatabase.DeleteAsset(path); // świeży wariant przy każdym generowaniu
            var inst = (GameObject)PrefabUtility.InstantiatePrefab(basePrefab);
            inst.name = name;
            inst.GetComponent<Collider>().sharedMaterial = pm;
            inst.GetComponent<Renderer>().sharedMaterial = mat;
            SetBlockFields(inst.GetComponent<Block>(), density, strength);
            var asset = PrefabUtility.SaveAsPrefabAsset(inst, path);
            UnityEngine.Object.DestroyImmediate(inst);
            return asset;
        }

        static void SetBlockFields(Block block, float density, float strength)
        {
            var so = new SerializedObject(block);
            so.FindProperty("density").floatValue = density;
            so.FindProperty("strength").floatValue = strength;
            so.ApplyModifiedPropertiesWithoutUndo();
        }

        static GameObject TargetPrefab(PhysicsMaterial pm, Material mat)
        {
            var go = GameObject.CreatePrimitive(PrimitiveType.Sphere);
            go.name = "Cel";
            go.transform.localScale = Vector3.one * 0.7f;
            var rb = go.AddComponent<Rigidbody>();
            rb.mass = 1f;
            rb.angularDamping = 0.5f;
            var t = go.AddComponent<Target>();
            var so = new SerializedObject(t);
            so.FindProperty("strength").floatValue = 3f;
            so.ApplyModifiedPropertiesWithoutUndo();
            go.GetComponent<Collider>().sharedMaterial = pm;
            go.GetComponent<Renderer>().sharedMaterial = mat;
            return SavePrefab(go, "Cel");
        }

        static GameObject ProjectilePrefab(PhysicsMaterial pm, Material mat)
        {
            var go = GameObject.CreatePrimitive(PrimitiveType.Sphere);
            go.name = "Pocisk";
            go.transform.localScale = Vector3.one * 0.6f;
            var rb = go.AddComponent<Rigidbody>();
            rb.mass = 3f;
            rb.linearDamping = 0f;
            rb.angularDamping = 0.5f;
            rb.collisionDetectionMode = CollisionDetectionMode.Discrete; // krok 6.1 - do zmiany w eksperymencie
            rb.interpolation = RigidbodyInterpolation.None;              // krok 6.2 - do zmiany w eksperymencie
            go.GetComponent<Collider>().sharedMaterial = pm;
            go.GetComponent<Renderer>().sharedMaterial = mat;
            return SavePrefab(go, "Pocisk");
        }

        static GameObject SavePrefab(GameObject go, string name)
        {
            string path = $"{PrefabDir}/{name}.prefab";
            var asset = PrefabUtility.SaveAsPrefabAsset(go, path);
            UnityEngine.Object.DestroyImmediate(go);
            return asset;
        }

        // =====================================================================
        //  MATERIAŁY
        // =====================================================================

        static PhysicsMaterial PhysMat(string name, float dynamicFriction, float staticFriction, float bounciness,
            PhysicsMaterialCombine frictionCombine = PhysicsMaterialCombine.Average,
            PhysicsMaterialCombine bounceCombine = PhysicsMaterialCombine.Average)
        {
            string path = $"{PhysDir}/{name}.asset";
            var pm = AssetDatabase.LoadAssetAtPath<PhysicsMaterial>(path);
            if (pm == null)
            {
                pm = new PhysicsMaterial(name);
                AssetDatabase.CreateAsset(pm, path);
            }
            pm.dynamicFriction = dynamicFriction;
            pm.staticFriction = staticFriction;
            pm.bounciness = bounciness;
            pm.frictionCombine = frictionCombine;
            pm.bounceCombine = bounceCombine;
            EditorUtility.SetDirty(pm);
            return pm;
        }

        static Shader FindShader(string urpName, string fallback)
        {
            var s = Shader.Find(urpName);
            return s != null ? s : Shader.Find(fallback);
        }

        static Material GetOrCreateMat(string name, Shader shader)
        {
            string path = $"{MatDir}/{name}.mat";
            var m = AssetDatabase.LoadAssetAtPath<Material>(path);
            if (m == null)
            {
                m = new Material(shader);
                AssetDatabase.CreateAsset(m, path);
            }
            else if (m.shader != shader)
            {
                m.shader = shader;
            }
            return m;
        }

        static Material Mat(string name, Color c)
        {
            var m = GetOrCreateMat(name, FindShader("Universal Render Pipeline/Lit", "Standard"));
            m.color = c;
            if (m.HasProperty("_BaseColor")) m.SetColor("_BaseColor", c);
            if (m.HasProperty("_Smoothness")) m.SetFloat("_Smoothness", 0.3f);
            EditorUtility.SetDirty(m);
            return m;
        }

        static Material UnlitMat(string name, Color c)
        {
            var m = GetOrCreateMat(name, FindShader("Universal Render Pipeline/Unlit", "Unlit/Color"));
            m.color = c;
            if (m.HasProperty("_BaseColor")) m.SetColor("_BaseColor", c);
            EditorUtility.SetDirty(m);
            return m;
        }

        static Material TransparentMat(string name, Color c)
        {
            var m = Mat(name, c);
            m.SetFloat("_Surface", 1f);
            m.SetFloat("_Blend", 0f);
            m.SetOverrideTag("RenderType", "Transparent");
            m.SetFloat("_SrcBlend", (float)BlendMode.SrcAlpha);
            m.SetFloat("_DstBlend", (float)BlendMode.OneMinusSrcAlpha);
            m.SetFloat("_SrcBlendAlpha", (float)BlendMode.One);
            m.SetFloat("_DstBlendAlpha", (float)BlendMode.OneMinusSrcAlpha);
            m.SetFloat("_ZWrite", 0f);
            m.EnableKeyword("_SURFACE_TYPE_TRANSPARENT");
            m.renderQueue = (int)RenderQueue.Transparent;
            m.SetShaderPassEnabled("DepthOnly", false);
            EditorUtility.SetDirty(m);
            return m;
        }

        // =====================================================================
        //  POMOCNICZE
        // =====================================================================

        static void Lighting()
        {
            RenderSettings.ambientMode = AmbientMode.Trilight;
            RenderSettings.ambientSkyColor = new Color(0.62f, 0.68f, 0.78f);
            RenderSettings.ambientEquatorColor = new Color(0.45f, 0.46f, 0.48f);
            RenderSettings.ambientGroundColor = new Color(0.22f, 0.21f, 0.2f);
            RenderSettings.skybox = AssetDatabase.GetBuiltinExtraResource<Material>("Default-Skybox.mat");

            var lightGo = new GameObject("Directional Light");
            var light = lightGo.AddComponent<Light>();
            light.type = LightType.Directional;
            light.intensity = 1.2f;
            light.shadows = LightShadows.Soft;
            light.color = new Color(1f, 0.97f, 0.92f);
            lightGo.transform.rotation = Quaternion.Euler(50f, -35f, 0f);
        }

        static void EnsureFolders()
        {
            foreach (var f in new[] { Root, PrefabDir, MatDir, PhysDir, SceneDir })
            {
                if (AssetDatabase.IsValidFolder(f)) continue;
                string parent = Path.GetDirectoryName(f).Replace('\\', '/');
                AssetDatabase.CreateFolder(parent, Path.GetFileName(f));
            }
        }
    }
